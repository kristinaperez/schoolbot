const MAX_URL_LENGTH = 2048;

/**
 * Санитизирует пользовательский URL для безопасного внедрения в промпт.
 * Защита от prompt injection:
 * - валидация структуры через URL API;
 * - ограничение длины;
 * - удаление control-символов и переносов строк;
 * - экранирование потенциально опасных последовательностей (< > `).
 * @param {string} rawUrl
 * @returns {string} Безопасный URL
 */
function sanitizeSiteUrl(rawUrl) {
  if (typeof rawUrl !== 'string') {
    throw new Error('siteUrl must be a string');
  }

  let url = rawUrl.trim();

  // Ограничение длины
  if (url.length > MAX_URL_LENGTH) {
    url = url.slice(0, MAX_URL_LENGTH);
  }

  // Удаление control-символов (включая \n \r \t и другие), которые могут
  // "разорвать" инструкцию промпта и позволить вставить новые команды.
  // eslint-disable-next-line no-control-regex
  url = url.replace(/[\x00-\x1F\x7F]/g, '');

  // Экранирование символов, которые могут быть использованы для
  // имитации XML-тегов или markdown-разметки внутри URL.
  url = url
    .replace(/</g, '\uFF1C') // < → ＜ (полноширинный)
    .replace(/>/g, '\uFF1E') // > → ＞
    .replace(/`/g, '\uFF40'); // ` → ｀

  // Валидация структуры URL. Если scheme отсутствует — добавляем https://
  let parsed;
  try {
    parsed = new URL(url);
  } catch (_) {
    try {
      parsed = new URL(`https://${url}`);
    } catch (__) {
      throw new Error(`Invalid siteUrl: unable to parse "${rawUrl}"`);
    }
  }

  // Разрешаем только http/https — остальные схемы (javascript:, data:, ftp:)
  // могут быть использованы для инъекций.
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
    throw new Error(`Invalid siteUrl protocol: ${parsed.protocol}`);
  }

  return parsed.toString();
}

